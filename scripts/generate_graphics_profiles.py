"""Generate the native profile table from the launcher's embedded source of truth."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
def render(profiles):
    lines = ["// Generated by scripts/generate_graphics_profiles.py; edit config/graphics_profiles.json.",
         "#pragma once", "struct MclaProfileValue { const char* profile; const char* key; const char* value; };",
         "inline constexpr MclaProfileValue kMclaProfileValues[] = {"]
    for name, values in profiles.items():
        for key, value in values.items():
            lines.append("    {" + ", ".join(json.dumps(v) for v in (name, key, value)) + "},")
    lines += ["};", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    profiles = json.loads((root / "config/graphics_profiles.json").read_text(encoding="utf8"))
    (root / "src/graphics_profiles.h").write_text(render(profiles), encoding="ascii")
